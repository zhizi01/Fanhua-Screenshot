import { test, expect, type Page } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

async function clickImage(page: Page, x: number, y: number) {
  const box = (await page.getByTestId('editor-canvas').boundingBox())!
  await page.mouse.click(box.x + box.width * x, box.y + box.height * y)
}

test('工具设置、窗口识别与框选预览', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '繁花有图', exact: true })).toBeVisible()
  await mkdir('artifacts', { recursive: true })
  await page.setViewportSize({ width: 560, height: 460 })
  await page.screenshot({ path: 'artifacts/settings.png' })
  await expect(page.getByRole('switch', { name: '开机时自动启动' })).toBeDisabled()
  await page.setViewportSize({ width: 1140, height: 820 })
  await page.getByRole('button', { name: /开始截图/ }).click()
  await expect(page.getByTestId('capture-stage')).toBeVisible()
  await page.mouse.move(300, 220)
  await expect(page.getByTestId('capture-selection')).toBeVisible()
  await expect(page.getByText('灵感手记 · 演示窗口')).toBeVisible()
  await page.screenshot({ path: 'artifacts/capture.png' })
  await page.mouse.click(300, 220)
  await expect(page.getByTestId('editor-canvas')).toBeVisible()
  const size = await page.getByTestId('editor-canvas').evaluate((el: HTMLCanvasElement) => [el.width, el.height])
  expect(size).toEqual([1080, 660])
  await page.getByRole('button', { name: '关闭窗口不保存' }).click()
  await page.getByRole('button', { name: /开始截图/ }).click()
  await expect(page.locator('.screen-image')).toBeVisible()
  await page.mouse.move(600, 400)
  await page.mouse.down()
  await page.mouse.move(200, 200, { steps: 12 })
  await page.mouse.up()
  await expect(page.getByTestId('editor-canvas')).toBeVisible()
  expect(await page.getByTestId('editor-canvas').evaluate((el: HTMLCanvasElement) => el.width)).toBeGreaterThan(200)
  expect(errors).toEqual([])
})

test('文字重新编辑、三种序号、马赛克无损删除和导出', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/?view=preview')
  await expect(page.getByTestId('editor-canvas')).toBeVisible()
  await page.screenshot({ path: 'artifacts/preview.png' })
  await page.getByRole('button', { name: '进入编辑模式' }).click()
  await page.getByRole('button', { name: '文字工具' }).click()
  await clickImage(page, .32, .21)
  await page.getByRole('textbox', { name: '标注文字内容' }).fill('值得记录的瞬间')
  await page.getByRole('spinbutton', { name: '标注字号' }).fill('36')
  await page.getByRole('spinbutton', { name: '标注字号' }).press('Tab')
  await page.getByRole('button', { name: '颜色 #8063d5' }).click()
  await page.getByRole('button', { name: '序号工具' }).click()
  await clickImage(page, .32, .75)
  await page.getByRole('textbox', { name: '标注文字内容' }).fill('在这里，补充一点说明')
  await page.locator('.ant-select[aria-label="序号方式"]').click()
  await page.getByTitle('A, B, C · 字母', { exact: true }).click()
  await expect(page.getByRole('button', { name: '选择图层 A · 在这里，补充一点说明', exact: true })).toBeVisible()
  await page.locator('.ant-select[aria-label="序号方式"]').click()
  await page.getByTitle('壹, 贰, 叁 · 中文大写', { exact: true }).click()
  await expect(page.getByRole('button', { name: '选择图层 壹 · 在这里，补充一点说明', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '选择图层 值得记录的瞬间', exact: true }).click()
  await page.getByRole('textbox', { name: '标注文字内容' }).fill('这一刻，繁花有图')
  await expect(page.getByRole('button', { name: '选择图层 这一刻，繁花有图', exact: true })).toBeVisible()
  // Selection-free pixels must return byte-for-byte after deleting a mosaic.
  await page.getByRole('button', { name: '马赛克工具' }).click()
  const canvas = page.getByTestId('editor-canvas')
  await page.waitForTimeout(80)
  const before = await canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL())
  const box = (await canvas.boundingBox())!
  await page.mouse.move(box.x + box.width * .40, box.y + box.height * .44)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * .72, box.y + box.height * .64, { steps: 10 })
  await page.mouse.up()
  await expect(page.getByRole('button', { name: '选择图层 马赛克区域' })).toBeVisible()
  await page.getByRole('slider', { name: '打码强度' }).focus()
  await page.keyboard.press('End')
  await page.getByRole('button', { name: '选择工具' }).click()
  await page.waitForTimeout(80)
  expect(await canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL())).not.toBe(before)
  await page.getByRole('button', { name: '选择图层 马赛克区域' }).click()
  await page.getByRole('button', { name: '删除此标注' }).click()
  await page.waitForTimeout(80)
  expect(await canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL())).toBe(before)
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(page.getByRole('button', { name: '选择图层 马赛克区域' })).toBeVisible()
  await page.getByRole('button', { name: '重做', exact: true }).click()
  await expect(page.getByRole('button', { name: '选择图层 马赛克区域' })).toHaveCount(0)
  await page.getByRole('button', { name: '选择图层 这一刻，繁花有图', exact: true }).click()
  await page.screenshot({ path: 'artifacts/editor.png' })
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '保存图片', exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/繁花有图.*\.png$/)
  await download.saveAs('artifacts/edited-export.png')
  await page.getByRole('button', { name: '进入编辑模式' }).click()
  await expect(page.getByRole('button', { name: '文字工具' })).toHaveCount(0)
  await page.getByRole('button', { name: '进入编辑模式' }).click()
  await expect(page.getByRole('button', { name: '选择图层 这一刻，繁花有图', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
