'use strict'
const assert = require('node:assert/strict')
const { Arch } = require('builder-util')
const hook = require('./windows-target.cjs')
const config = require('../package.json')

assert.doesNotThrow(() => hook.assertWindowsHost('win32', 'x64'))
for (const platform of ['linux', 'darwin']) assert.throws(() => hook.assertWindowsHost(platform, 'x64'), /Windows/)
assert.throws(() => hook.assertWindowsHost('win32', 'arm64'), /x64/)
assert.doesNotThrow(() => hook({ electronPlatformName: 'win32', arch: Arch.x64 }))
for (const platform of ['linux', 'darwin']) assert.throws(() => hook({ electronPlatformName: platform, arch: Arch.x64 }), /仅生成 Windows/)
for (const arch of [Arch.ia32, Arch.arm64]) assert.throws(() => hook({ electronPlatformName: 'win32', arch }), /x64/)
assert.deepEqual(config.os, ['win32'])
assert.deepEqual(config.build.win.target, [{ target: 'nsis', arch: ['x64'] }])
assert.match(config.scripts.pack, /--win --x64 --dir/)
assert.match(config.scripts.dist, /--win nsis --x64/)
assert.equal(config.build.beforePack, 'scripts/windows-target.cjs')
console.log('Windows x64 构建入口与非 Windows 目标拒绝验证通过。')
